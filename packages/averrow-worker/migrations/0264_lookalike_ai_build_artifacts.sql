-- 0264_lookalike_ai_build_artifacts.sql
-- AI-build artifacts & covert exfil sinks (Lane 3 Phase 1).
-- Spec: docs/LANE3_AI_BUILD_ARTIFACTS_SPEC.md §3.4 / §5 (shadow mode).
--
-- The deterministic page scorer (lib/page-phishing-scorer.ts) grades a
-- lookalike's live HTML today on seven signals. Two evidence classes are
-- missing from it. (1) `offdomain_form_exfil` reads ONLY <form action>,
-- so a kit that ships credentials from inline script — fetch(),
-- XMLHttpRequest, navigator.sendBeacon() — to a Telegram bot or a
-- Discord webhook is invisible to the strongest signal we have, and a
-- live credential harvester sits in the queue scoring MEDIUM. (2) Kits
-- generated by an AI site builder and shipped unreviewed leak structural
-- build artifacts (unrendered template tokens, default scaffold titles,
-- model refusal text, agent to-do comments) that are deterministic,
-- literal, and cheap to match.
--
-- These six columns persist that new evidence in SHADOW MODE. Nothing
-- here feeds page_phishing_score, threat_level, credentialHarvest or
-- alert triage in this phase — the scorer computes the new signals into
-- separate result fields and the page-analysis pass writes them to these
-- columns ONLY. The point is to measure firing rates, lift against the
-- existing high-confidence label set, and the false-positive rate on
-- brand-canonical homepages BEFORE any of it is allowed to escalate an
-- operator-facing verdict (spec §5.1-§5.3).
--
-- Class A (synthetic build) is capped at 20 points in the shadow delta
-- and can never set a floor: it is a proxy for disposable mass
-- production, not for malice, and a legitimate small business on an AI
-- site builder trips it.
--
-- No index, deliberately: these are low-cardinality / JSON columns read
-- once per TTL by a cachedValue-wrapped diagnostics pass over
-- lookalike_domains, which is a small bounded table. An index here would
-- be write cost with no reader.
--
-- Additive only — ADD COLUMN, never DROP/ALTER (CLAUDE.md §8). NULL for
-- every existing row until the next successful page-analysis pass
-- touches it, and NULL forever on rows whose fetch fails (the failure
-- path deliberately preserves prior verdicts and writes none of these).
--   page_ai_signals     JSON array of the shadow signal keys that fired
--                       on the last SUCCESSFUL page analysis, e.g.
--                       ["covert_exfil_sink","default_scaffold_title"].
--                       Written on every successful analysis — '[]' when
--                       nothing fired — so a non-NULL value is also the
--                       marker that the last analysis reached the scorer.
--                       NULL means never successfully analyzed.
--   page_score_delta    Would-be score contribution of page_ai_signals:
--                       min(20, sum of Class A weights) + Class B + C.
--                       NOT added to page_phishing_score in this phase.
--                       0 when nothing fired. NULL when never analyzed.
--   page_generator      <meta name="generator"> content from the last
--                       successful analysis, truncated to 64 chars, or
--                       NULL when the page declared none. Grouping
--                       dimension only — WEIGHT ZERO, never scored
--                       (spec §8 item 5: WordPress alone is ~43% of the
--                       web).
--   page_exfil_sink     Host of the covert / relay exfil sink matched by
--                       covert_exfil_sink or form_relay_sink, e.g.
--                       'api.telegram.org'. NULL when neither fired.
--                       HOST ONLY, bounded to 253 chars (max legal DNS
--                       name) at the extractor.
--
--   ** CONSTRAINT — THE FULL SINK URL MUST NEVER BE PERSISTED, HERE OR
--   ** IN ANY COLUMN, LOG, EVIDENCE BLOB OR EXPORT.
--   ** `api.telegram.org/bot<id>:<token>/…` and
--   ** `discord.com/api/webhooks/<id>/<token>` are LIVE CREDENTIALS, not
--   ** identifiers. Anyone holding one can post to the attacker's channel
--   ** — and for Telegram, read from it — which means storing it turns
--   ** this table into a credential store for third-party channels,
--   ** exposes the platform to unauthorized-access liability, and tips
--   ** off the operator the moment it is used. Store the HOST
--   ** (page_exfil_sink) and the NON-SECRET LEADING ID
--   ** (page_exfil_sink_id) and nothing else; the id alone is a
--   ** sufficient pivot key for cross-brand kit clustering.
--   ** lib/page-phishing-scorer.ts honours this today: the digit walk in
--   ** digitsAfterMarker stops at the first non-digit, so it terminates
--   ** at the ':' (Telegram) or '/' (Discord) that begins the token, and
--   ** the 64-char evidence literal is the matched PREFIX, never the
--   ** reference. Lane 2's shared extractor inherits this constraint —
--   ** it may not widen the walk past the token boundary.
--   page_exfil_sink_id  Bot or webhook id extracted from that sink —
--                       the Telegram bot id from
--                       api.telegram.org/bot<id>:<token>/ or the Discord
--                       webhook id from /api/webhooks/<id>/. This is a C2
--                       identifier in the ordinary IOC sense and the
--                       pivot key for cross-brand kit clustering: one bot
--                       serves many kits. NULL when no id was extractable.
--   page_evidence       JSON object mapping each fired signal key to the
--                       matched literal, truncated to 64 chars, e.g.
--                       {"llm_refusal_leakage":"as an ai language model"}.
--                       Without it an analyst adjudicating a firing has
--                       nothing to examine, because only a SHA-256 of the
--                       page body is retained (spec §5.5). NULL when
--                       nothing fired.

ALTER TABLE lookalike_domains ADD COLUMN page_ai_signals TEXT;
ALTER TABLE lookalike_domains ADD COLUMN page_score_delta INTEGER;
ALTER TABLE lookalike_domains ADD COLUMN page_generator TEXT;
ALTER TABLE lookalike_domains ADD COLUMN page_exfil_sink TEXT;
ALTER TABLE lookalike_domains ADD COLUMN page_exfil_sink_id TEXT;
ALTER TABLE lookalike_domains ADD COLUMN page_evidence TEXT;
