-- 0294_hosting_provider_malformed_id_cleanup.sql — fold legacy
-- "hp_AS<N> <name>" hosting_providers rows into their canonical ASN row.
--
-- A legacy ip-api enrichment path (stopped ~2026-04-28) stored the whole
-- `geo.as` string as the provider identity, e.g.
--
--   id  = 'hp_AS200350 Yandex.Cloud LLC'
--   asn = 'AS200350 Yandex.Cloud LLC'
--
-- Every current writer (lib/geoip.ts upsertHostingProvider,
-- agents/cartographer.ts, workflows/cartographerBackfill.ts) keeps only
-- `split(' ')[0]`, so no new rows of this shape appear. 0144 hand-cleaned
-- 16 of them; this migration handles the remaining tail set-based.
--
-- Prod probe 2026-10-14 (read-only): 48 rows match `id LIKE 'hp_AS% %'`
-- (every one has id = 'hp_' || asn), 1,108 threats point at them, 41 have a
-- canonical twin (a row whose asn = the leading token, all under the
-- 'hp_AS<N>' id), 7 have none. 435 threat_cube_provider rows across 232
-- hour buckets (oldest 2026-03-14) carry malformed ids. 2,997 threats carry
-- a space in threats.asn.
--
-- ── References to hosting_providers.id (audited) ─────────────────────
--   threats.hosting_provider_id      the ONLY declared FK (sqlite_master in
--                                    prod + migrations grep) — repointed.
--   threat_cube_provider             no FK, PK includes the id — MERGED
--                                    (see step 4).
--   provider_threat_stats            keyed by provider_name, not id —
--                                    recomputed every cartographer tick.
--   infrastructure_clusters          hosting_provider_ids JSON snapshot,
--     .hosting_provider_ids          regenerated by every NEXUS run (0141
--                                    precedent) — left alone.
--   agent_outputs                    historical JSON, no FK — left alone.
--     .related_provider_ids
--   daily_snapshots                  entity_type='provider' rows keyed by
--     (entity_id = provider id)      the id (PK (date, entity_type,
--                                    entity_id)); 63 rows per malformed id
--                                    in prod — MERGED like the cube (step
--                                    4b). Brand rows' dominant_hosting_provider
--                                    holds a provider NAME, not an id —
--                                    untouched.
--
-- ── Prod audit 2026-10-14 (read-only probes) ─────────────────────────
--   * No malformed row has is_bulletproof = 1 or abuse_contact_id set (0
--     rows), so nothing is carried onto the canonical row.
--     reputation_score is set on all 48; twins carry their own and the
--     scorer recomputes, so it is dropped with the malformed row.
--   * All 2,997 spaced threats.asn values are 'AS<digits> <name>'; 0 odd
--     shapes. Step 5 still guards on the AS<digits> prefix.
--   * Moved active threats per canonical row max out at 141, below Flight
--     Control's 200 provider-escalation floor — the recount cannot raise a
--     spurious platform_provider_escalation.
--   * L1: NEXUS compares each bridge cluster's IPs/ASNs/cert-serials to its
--     prior-run fingerprint; a cluster whose stored fingerprint held a
--     spaced asn may emit ONE infra_movement pivot_detected event on the
--     first run after step 5 normalises threats.asn. One-off, expected.
--
-- ── Idempotency / D1 runner notes ────────────────────────────────────
-- No BEGIN/COMMIT (D1 rejects them). A regular staging table is used, not a
-- TEMP one — D1 does not keep TEMP tables across statements (0141
-- precedent). The staging table is rebuilt from hosting_providers on every
-- run, so once the malformed rows are gone a second run finds nothing and
-- every statement below is a no-op.
--
-- A malformed row whose canonical target cannot be resolved (an id
-- 'hp_AS<N>' already taken by a row with a different asn — 0 in prod) is
-- dropped from the staging set and left untouched rather than repointed to
-- NULL.

DROP TABLE IF EXISTS _hp_malformed_0294;

CREATE TABLE _hp_malformed_0294 (
  old_id       TEXT PRIMARY KEY,
  prefix       TEXT NOT NULL,
  remainder    TEXT,
  country      TEXT,
  canonical_id TEXT
);

-- The identity is parsed from the id (always 'hp_' || <full ip-api string>)
-- so the row is found even if its asn was later nulled. prefix = the
-- leading 'AS<N>' token, remainder = the organisation name after it.
INSERT INTO _hp_malformed_0294 (old_id, prefix, remainder, country)
SELECT id,
       substr(id, 4, instr(id, ' ') - 4),
       trim(substr(id, instr(id, ' ') + 1)),
       country
FROM hosting_providers
WHERE id LIKE 'hp_AS% %'
  AND substr(id, 4, instr(id, ' ') - 4) GLOB 'AS[0-9]*'
  AND substr(id, 4, instr(id, ' ') - 4) NOT GLOB 'AS*[^0-9]*';

-- 1. Canonical row for malformed rows with no twin. ON CONFLICT DO NOTHING
--    covers both the id PK and UNIQUE(asn) (incl. two malformed rows that
--    share one ASN). The twin test is "a row WHERE asn = prefix", whatever
--    its id, so a legacy-id twin is reused rather than duplicated.
INSERT INTO hosting_providers (id, name, asn, country)
SELECT 'hp_' || m.prefix,
       COALESCE(NULLIF(m.remainder, ''), m.prefix),
       m.prefix,
       m.country
FROM _hp_malformed_0294 m
WHERE NOT EXISTS (SELECT 1 FROM hosting_providers h WHERE h.asn = m.prefix)
ON CONFLICT DO NOTHING;

-- 2. Resolve the target: always the row WHERE asn = prefix.
UPDATE _hp_malformed_0294
SET canonical_id = (
  SELECT h.id FROM hosting_providers h WHERE h.asn = _hp_malformed_0294.prefix
);

DELETE FROM _hp_malformed_0294
WHERE canonical_id IS NULL OR canonical_id = old_id;

-- 3. Repoint threats (idx_threats_provider on hosting_provider_id).
UPDATE threats
SET hosting_provider_id = (
  SELECT m.canonical_id FROM _hp_malformed_0294 m
  WHERE m.old_id = threats.hosting_provider_id
)
WHERE hosting_provider_id IN (SELECT old_id FROM _hp_malformed_0294);

-- 4. Merge threat_cube_provider. Its PK includes hosting_provider_id, so a
--    plain UPDATE would collide with an existing canonical-id row for the
--    same (hour, type, severity, feed). The rows are MERGED (counts added)
--    rather than deleted: buildProviderCubeForHour is upsert-only and the
--    cube-healer rebuilds just 30 days, while malformed-id buckets go back
--    to 2026-03-14 — deleting them would lose those counts permanently.
--    The two sides count disjoint threat sets (each threat had exactly one
--    provider id), so the sum is the correct post-repoint value; inside
--    the healer window the next rebuild overwrites it with the same number
--    recomputed from the repointed threats.
INSERT INTO threat_cube_provider
  (hour_bucket, hosting_provider_id, threat_type, severity, source_feed,
   threat_count, updated_at)
SELECT c.hour_bucket, m.canonical_id, c.threat_type, c.severity, c.source_feed,
       SUM(c.threat_count), datetime('now')
FROM threat_cube_provider c
JOIN _hp_malformed_0294 m ON m.old_id = c.hosting_provider_id
WHERE 1
GROUP BY c.hour_bucket, m.canonical_id, c.threat_type, c.severity, c.source_feed
ON CONFLICT(hour_bucket, hosting_provider_id, threat_type, severity, source_feed)
DO UPDATE SET
  threat_count = threat_cube_provider.threat_count + excluded.threat_count,
  updated_at   = excluded.updated_at;

DELETE FROM threat_cube_provider
WHERE hosting_provider_id IN (SELECT old_id FROM _hp_malformed_0294);

-- 4b. Merge daily_snapshots provider rows the same way: PK (date,
--     entity_type, entity_id) collides on a plain UPDATE. Daily counters
--     add (disjoint threat sets); the canonical row keeps its own
--     dominant_threat_type and only takes the malformed side's when its own
--     is NULL. Past days are never recomputed, so deleting instead would
--     lose history.
INSERT INTO daily_snapshots
  (date, entity_type, entity_id, new_threats, active_threats,
   remediated_threats, dominant_threat_type)
SELECT s.date, 'provider', m.canonical_id,
       SUM(s.new_threats), SUM(s.active_threats), SUM(s.remediated_threats),
       MAX(s.dominant_threat_type)
FROM daily_snapshots s
JOIN _hp_malformed_0294 m ON m.old_id = s.entity_id
WHERE s.entity_type = 'provider'
GROUP BY s.date, m.canonical_id
ON CONFLICT(date, entity_type, entity_id) DO UPDATE SET
  new_threats          = daily_snapshots.new_threats + excluded.new_threats,
  active_threats       = daily_snapshots.active_threats + excluded.active_threats,
  remediated_threats   = daily_snapshots.remediated_threats + excluded.remediated_threats,
  dominant_threat_type = COALESCE(daily_snapshots.dominant_threat_type, excluded.dominant_threat_type);

DELETE FROM daily_snapshots
WHERE entity_type = 'provider'
  AND entity_id IN (SELECT old_id FROM _hp_malformed_0294);

-- 5. Normalise threats.asn to the leading token. Plans as a covering scan
--    of idx_threats_asn (partial, asn IS NOT NULL): ~0.8M index entries,
--    ~120 ms in prod, 2,997 rows written. One-off.
UPDATE threats
SET asn = substr(asn, 1, instr(asn, ' ') - 1)
WHERE asn IS NOT NULL
  AND asn LIKE '% %'
  AND instr(asn, ' ') > 1
  AND substr(asn, 1, instr(asn, ' ') - 1) GLOB 'AS[0-9]*'
  AND substr(asn, 1, instr(asn, ' ') - 1) NOT GLOB 'AS*[^0-9]*';

-- 6. Recompute the pre-computed counts for the affected canonical rows,
--    same definition as lib/provider-counts.ts. trend_7d / trend_30d are
--    left to their single writer, lib/provider-trends.ts.
UPDATE hosting_providers
SET active_threat_count = (
      SELECT COUNT(*) FROM threats
      WHERE threats.hosting_provider_id = hosting_providers.id
        AND threats.status = 'active'
    ),
    total_threat_count = (
      SELECT COUNT(*) FROM threats
      WHERE threats.hosting_provider_id = hosting_providers.id
    )
WHERE id IN (SELECT canonical_id FROM _hp_malformed_0294);

-- 7. Delete the malformed rows. The NOT EXISTS guard keeps the FK from
--    aborting the migration if a threat was re-pointed at a malformed id
--    between steps 3 and 7; such a row survives to the next run.
DELETE FROM hosting_providers
WHERE id IN (SELECT old_id FROM _hp_malformed_0294)
  AND NOT EXISTS (
    SELECT 1 FROM threats WHERE threats.hosting_provider_id = hosting_providers.id
  );

DROP TABLE _hp_malformed_0294;
