/**
 * Shared seed for the NEXUS lane tests (nexus-threat-lanes / parity /
 * cluster-retirement). Seeds the threats table of a FULLY MIGRATED schema
 * (openMigratedDb) so the lane SQL runs against real columns, the
 * ip_subnet24 generated column, and the real index set.
 */

import type { SqliteDb } from "./sqlite-d1-harness";

export interface SeedThreat {
  id: string;
  threat_type?: string;
  domain?: string;
  brand?: string | null;
  ip?: string | null;
  asn?: string | null;
  cc?: string | null;
  status?: string;
  serial?: string | null;
  san?: string | null;
  registrar?: string | null;
  campaign?: string | null;
  /** first_seen, default 2 days ago */
  daysAgo?: number;
  cluster_id?: string | null;
}

export function insertThreats(db: SqliteDb, rows: SeedThreat[]): void {
  const stmt = db.prepare(
    `INSERT INTO threats (id, source_feed, threat_type, malicious_domain, target_brand_id,
                          ip_address, asn, country_code, status, ssl_cert_serial, ssl_san_hash,
                          registrar, campaign_id, first_seen, cluster_id)
     VALUES (?, 'test', ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, datetime('now', ?), ?)`,
  );
  for (const r of rows) {
    stmt.run(
      r.id, r.threat_type ?? "phishing", r.domain ?? `${r.id}.example`, r.brand === undefined ? "brand_0" : r.brand,
      r.ip ?? null, r.asn ?? null, r.cc === undefined ? "US" : r.cc, r.status ?? "active",
      r.serial ?? null, r.san ?? null, r.registrar ?? null, r.campaign ?? null,
      `-${r.daysAgo ?? 2} days`, r.cluster_id ?? null,
    );
  }
}

/** n threats generated by `make(i)`. */
export function many(n: number, make: (i: number) => SeedThreat): SeedThreat[] {
  return Array.from({ length: n }, (_, i) => make(i));
}

/**
 * The canonical scenario: shared-infra noise the reworked lanes must
 * ignore, plus one genuine operation per lane.
 */
export function seedScenario(db: SqliteDb): void {
  insertThreats(db, [
    // Cloudflare ASN-only phishing — 40 threats, many brands: pre-fix the
    // ASN lane's biggest, highest-confidence cluster. Must not cluster.
    ...many(40, (i) => ({ id: `cf_${i}`, asn: "AS13335", brand: `b${i % 30}`, cc: i % 2 ? "CA" : "US" })),
    // Same network, malformed asn string — normalises to AS13335 → excluded.
    ...many(12, (i) => ({ id: `cfm_${i}`, asn: "AS13335 Cloudflare, Inc.", brand: `b${i}` })),
    // IP-reputation sightings on an ordinary ASN — not an operation.
    ...many(15, (i) => ({ id: `scan_${i}`, threat_type: "scanning", asn: "AS4134", brand: null, cc: "CN" })),
    // Genuine ASN-only group: AS4837 malware, 12 active (incl. 3 with the
    // malformed spelling) + 4 inactive that must not count or stamp.
    ...many(9, (i) => ({ id: `cu_${i}`, threat_type: "malware_distribution", asn: "AS4837", brand: `m${i % 3}`, cc: "CN" })),
    ...many(3, (i) => ({ id: `cum_${i}`, threat_type: "malware_distribution", asn: "AS4837 China Unicom, Ltd", brand: "m0", cc: "HK" })),
    ...many(4, (i) => ({ id: `cuold_${i}`, threat_type: "malware_distribution", asn: "AS4837", brand: "m0", cc: "CN", status: "remediated" })),
    // AWS Global Accelerator parking hub: one IP, 160 brands. Shared ASN
    // AND over the hub threshold — must not become a per-IP cluster.
    ...many(160, (i) => ({ id: `hub_${i}`, ip: "13.248.169.48", asn: "AS16509", brand: `h${i}`, cc: "US" })),
    // Same hub shape with the ASN unknown — excluded by the hub threshold alone.
    ...many(155, (i) => ({ id: `hubx_${i}`, ip: "198.51.100.200", asn: null, brand: `x${i}`, cc: null })),
    // Under the hub threshold but on Cloudflare anycast — excluded by the
    // shared-ASN filter alone.
    ...many(10, (i) => ({ id: `cfip_${i}`, ip: "104.21.0.9", asn: "AS13335", brand: `f${i}`, cc: "US" })),
    // Genuine per-IP operation: one IP, 4 brands, 8 threats, single ASN.
    ...many(8, (i) => ({ id: `ip_${i}`, ip: "203.0.113.7", asn: "AS9009", brand: `p${i % 4}`, cc: "NL" })),
    // /24 on OVH (shared infra, newly covered by the broadened list) — excluded.
    ...many(10, (i) => ({ id: `ovh_${i}`, ip: `51.38.10.${i + 1}`, asn: "AS16276", brand: `o${i % 5}`, cc: "FR" })),
    // Genuine /24 operation: 3 IPs × 3 threats on AS9999, 3 brands.
    ...many(9, (i) => ({ id: `sn_${i}`, ip: `74.115.51.${(i % 3) + 10}`, asn: "AS9999", brand: `s${i % 3}`, cc: i < 6 ? "DE" : "PL" })),
    // Cert-serial reuse across 3 domains (on Cloudflare — still evidence).
    ...many(3, (i) => ({ id: `cert_${i}`, serial: "0a1b2c3d4e5f60718293", asn: "AS13335", brand: `c${i}`, cc: "US" })),
  ]);
}
